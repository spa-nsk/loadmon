// Package itilium — HTTP-клиент к 1С:ITILIUM (Service Desk / ITSM на
// платформе «1С:Предприятие 8»).
//
// # Источники API
//
// Официальная документация (Деснол / 1c-itilium.ru), сверено 2026-11:
//
//  1. Внешний HTTP-сервис обращений (релиз ≈5.0.0.5+), путь вида
//     `<публикация>/hs/externalapi/<метод>` — POST + JSON.
//     https://1c-itilium.ru/manual/admin/integration/instruktsiyapo-rabote-s-vneshnim-servisom
//  2. HTTP-сервис веб-портала (роль «Потребитель услуг»), путь вида
//     `<публикация>/hs/web-portal-api/<метод>` — GET/POST + JSON.
//     https://1c-itilium.ru/manual/admin/integration/external_systems
//     (раздел «Пример интеграции с внешним порталом…»; адрес публикации —
//     https://1c-itilium.ru/manual/web_portal_user_nextjs).
//  3. SOAP-сервисы IT_DataGetting (чтение документов) и custom_actions
//     (произвольная обработка) в этом пакете не реализованы — они требуют
//     WSDL/XDTO и пользовательской обработки на стороне 1С.
//
// # Что покрывает пакет
//
// ExternalClient — список/детали/смена состояния обращений, справочники
// для отборов (рабочие группы, сотрудники, клиенты, услуги…), файлы.
// PortalClient — сценарий потребителя услуг: список КЕ/услуг/категорий,
// создание обращения, комментарии/файлы, подтверждение.
//
// # Чего в публичном HTTP API нет
//
// Выгрузки CMDB-активов (серверы, СХД, блейд-корзины и т.п.) через эти
// HTTP-сервисы не описаны. В loadmon они по-прежнему берутся из Excel-
// выгрузок пакетом itilliumimport. Импорт В ITILIUM из SCOM/SCCM/AD/Excel
// — односторонняя загрузка в 1С, не API для чтения наружу.
//
// # Аутентификация и публикация
//
// Типовая публикация 1С на IIS/Apache отдаёт HTTP-сервисы под
// `/<имя_публикации>/hs/...`. Клиент использует HTTP Basic (пользователь
// информационной базы 1С с нужной ролью). Неверный BaseURL или префикс
// сервиса — самая частая причина 404; сверьте с .vrd / UpdateVRD.
