package cmdb

import (
	"fmt"
	vsphere "loadmon/vspheremetrics"

	oneview "github.com/spa-nsk/oneview2"
)

// UpdateServerInventory — универсальная точка синхронизации справочника
// серверов (models.ServerSprRecords) и связанных с ним таблиц
// (models.VMSprRecord — виртуальные машины, models.ServerHardware —
// конфигурации аппаратных серверов и гипервизоров) со всеми источниками
// данных проекта, согласно следующей логике владения данными:
//
//  1. Виртуальные машины и гипервизоры (ServerSprRecords.Type == 1 и 2) —
//     обновляются из VMware vSphere (закэшированный пул
//     vspheremetrics.GetGlobalVMInfrastructure(), опрашиваемый govmomi).
//     Для ВМ это единственный источник. Для гипервизоров - основной
//     источник роли/принадлежности к Vcenter/Datacenter/Cluster.
//  2. Аппаратные серверы (Type == 0), включая оборудование, которое СЕЙЧАС
//     является гипервизором (Type == 2) - обновляются из HP OneView
//     (конфигурация: процессоры, память, диски, серийные номера) и из
//     Zabbix (сетевые адреса, факт присутствия в мониторинге). HP OneView
//     - основной источник для определения "передачи владения" между ролями
//     гипервизор/физический сервер (см. cmdb.ImportServerSprFromHW).
//  3. Если по конкретному серверу нет данных о его роли гипервизора в HP
//     OneView (например, OneView не знает о сервере вовсе, либо его поле
//     OperatingSystem не заполнено/не отражает факт установки ESXi
//     корректно - это распространённая проблема OneView, см. комментарий к
//     cmdb.ImportServerSprFromHW) - роль и связанные с ней поля
//     (Vcenter/Datacenter/Cluster/ClusterId/OS) актуализируются данными
//     VMware в необходимом объёме через cmdb.UpdateHWHostInfo. Она же
//     подхватывает и создаёт запись в ServerSprRecords для хостов, которые
//     видны в vSphere, но по каким-то причинам никогда не появлялись со
//     стороны HP OneView.
//
// Порядок вызова здесь важен и соответствует правилу "HP OneView решает,
// чья сейчас роль, VMware её подтверждает/дополняет":
//
//  1. cmdb.UpdateHwSprHP() - HP OneView: конфигурации аппаратных серверов
//     (ServerHardware) + ServerSprRecords, включая "передачу владения"
//     ролью гипервизор -> физический сервер и обратно внутри
//     cmdb.ImportServerSprFromHW (вызывается из UpdateHwSprHPServers).
//  2. cmdb.UpdateSprVM() - VMware: справочник виртуальных машин
//     (VMSprRecord) и связанные записи ServerSprRecords с Type == 1.
//  3. cmdb.UpdateHWHostInfo() - VMware: подтверждение/актуализация записей
//     ServerSprRecords с Type == 2 для хостов, реально присутствующих в
//     пуле vSphere прямо сейчас - выполняется ПОСЛЕ HP OneView, чтобы
//     восполнить те случаи, когда OneView не смог корректно определить/
//     сохранить роль гипервизора (ненадёжное поле OS в OneView).
//     UpdateHWHostInfo сама никогда не понижает Type (см. её комментарий) -
//     этим шаг 3 не может "затереть" уже выполненную в шаге 1 демоцию
//     оборудования, у которого гипервизор был снесён.
//
// ⚠️ Важное уточнение к пункту 3 (найдено при аудите этой функции): фраза
// "UpdateHWHostInfo никогда не понижает Type" верна буквально, но раньше
// шаг 1 (ImportServerSprFromHW, HP OneView) и шаг 3 (UpdateHWHostInfo,
// VMware) вызывались из НЕЗАВИСИМЫХ, несвязанных циклов - каждый брал
// СОБСТВЕННЫЙ снапшот vsphere.GetGlobalVMInfrastructure() и это было не
// важно. В этой функции они вызываются ПОСЛЕДОВАТЕЛЬНО в рамках одного
// потока выполнения - если бы каждый шаг по-прежнему брал свой снапшот, то
// демоция роли, принятая на шаге 1 по снапшоту T1 (хост отсутствовал в
// HostBySNMapList), могла бы быть немедленно отменена на шаге 3, если
// фоновый опрос vCenter успел подменить глобальный снапшот на T2 (хост
// снова появился), в котором хост снова присутствует в HostMapList -
// то есть шаг 3 заново проставил бы Type=2 в рамках ОДНОГО И ТОГО ЖЕ
// цикла синхронизации, хотя буквально "не понижал Type". Поэтому ниже
// снапшот vSphere берётся ОДИН РАЗ в начале UpdateServerInventory и
// передаётся явным параметром infra в обе стороны (UpdateHwSprHPServersInfra
// и UpdateHWHostInfoInfra) - оба шага гарантированно видят одно и то же
// согласованное состояние vSphere.
//
// Zabbix ("аппаратные серверы обновляются из HP OneView и Zabbix") -
// НЕ вызывается из этой функции: реальная реализация опроса Zabbix
// (zabbix.Get10MinutesHistory, пакет loadmon/zabbix) сама импортирует
// loadmon/cmdb (см. zabbix/zabbixupdate.go, importHostDB и связывание с
// ServerSprRecords по имени) - добавление обратного импорта loadmon/zabbix
// сюда создало бы цикл импортов пакетов Go, что недопустимо. Поэтому вызов
// zabbix.Get10MinutesHistory() по-прежнему должен идти отдельным шагом со
// стороны вызывающего кода (см. tickerZabbix в metrics_grpc/metrics_grpc.go) -
// по возможности после этой функции, чтобы Zabbix обновлял IP-адреса и
// факт присутствия в мониторинге уже по актуальному состоянию справочника
// серверов.
//
// ⚠️ Функция не вызывается ни из одного текущего рабочего цикла - как и
// cmdb.UpdateHWHostInfo, подключение вызова (замена по отдельности
// вызываемых сейчас cmdb.UpdateHwSprHP()/cmdb.UpdateSprVM() в
// metrics_grpc/metrics_grpc.go на один вызов UpdateServerInventory(), плюс
// раскомментирование самой UpdateHWHostInfo) - отдельное осознанное
// решение, которое нужно проверить на реальных данных перед включением.
func UpdateServerInventory() {
	fmt.Println("Синхронизация справочника серверов: начало")

	ov := oneview.GetGlobalOVInfrastructure()

	// Единый снапшот vSphere на весь цикл - см. пояснение выше про
	// рассинхронизацию при последовательном вызове HP OneView- и
	// VMware-сторон синхронизации. Передаётся явным параметром в обе
	// стороны вместо того, чтобы каждая брала свой снапшот самостоятельно.
	infra := vsphere.GetGlobalVMInfrastructure()

	fmt.Println("Синхронизация справочника серверов: HP OneView (аппаратные серверы, передача владения ролью)")
	UpdateHwSprHPBladeSystem(ov)
	UpdateHwSprHPServersInfra(ov, infra)

	fmt.Println("Синхронизация справочника серверов: VMware (виртуальные машины)")
	UpdateSprVM()

	fmt.Println("Синхронизация справочника серверов: VMware (подтверждение/дополнение данных гипервизоров)")
	UpdateHWHostInfoInfra(infra)

	fmt.Println("Синхронизация справочника серверов: завершено")
}
