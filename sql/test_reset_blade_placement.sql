-- Справочники площадок и шкафов (cmdb_datacenter_site / cmdb_rack_cabinet)
-- этим скриптом НЕ трогаются намеренно - общие данные, разделяемые с
-- размещением серверов/СХД, а не артефакт именно импорта блейд-корзин.
-- Повторный импорт Итиллиум сам найдёт/создаст нужные записи через
-- resolveRackCabinet (itilliumimport/resolvecabinet.go).

-- Дочерние блейд-сервера (models.ServerHardware с FormFactor=2,
-- BladeSystemId>0) этим скриптом тоже не трогаются - их собственное
-- размещение (если оно есть отдельно от корзины) зачищается скриптом
-- test_reset_serverhardware_placement.sql. Связь BladeSystemId (какой
-- сервер в какой корзине установлен) - это НЕ размещение в пространстве
-- (шкаф/юнит), а структурная принадлежность, этот скрипт её не трогает.

