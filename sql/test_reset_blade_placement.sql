-- =============================================================================
-- Зачистка данных размещения справочника блейд-корзин (models.BladeSystems,
-- таблица blade_systems) для проверки корректной загрузки размещения из
-- файла Итиллиум и проверки отображения (bladesystemslist.tpl/
-- bladesystemsedit.tpl, канвасы /admin/hwinfra и /admin/infrastructure).
--
-- В отличие от СХД (см. test_reset_storage_placement.sql), у блейд-корзин
-- НЕТ отдельной таблицы-связки размещения - RackCabinetId/StartUnitPos/
-- EndUnitPos/SizeUnit хранятся прямо в таблице blade_systems как обычные
-- (не осиротевшие) поля текущей модели, поэтому здесь один шаг вместо двух.
--
-- Совместим с обоими драйверами БД проекта (postgres и sqlite3).
-- =============================================================================

-- Зачистка размещения ВСЕХ блейд-корзин:
UPDATE blade_systems
SET rack_cabinet_id = 0, start_unit_pos = 0, end_unit_pos = 0, size_unit = 0
WHERE rack_cabinet_id > 0 OR start_unit_pos > 0 OR end_unit_pos > 0 OR size_unit > 0;

