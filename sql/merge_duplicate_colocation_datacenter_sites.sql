-- Шаг 1. НАЙТИ все пары "короткое имя" / "адрес с (короткое имя)" - чтобы
-- убедиться, что merge ниже относится именно к вашему случаю, и посмотреть
-- реальные id (для примера пользователя - "ЦОД М1" / "...(ЦОД М1)...").
SELECT
    short.id   AS short_id,   short.name   AS short_name,
    addr.id    AS addr_id,    addr.name    AS addr_name
FROM cmdb_datacenter_site short
JOIN cmdb_datacenter_site addr
    ON addr.name LIKE '%(' || short.name || ')%'
WHERE short.id <> addr.id
ORDER BY short.name;

