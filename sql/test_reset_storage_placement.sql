-- Шаг 2. Обезвредить "осиротевшие" legacy-колонки storage_systems (если они
-- ещё физически существуют в вашей БД), чтобы миграция при следующем старте
-- приложения не восстановила из них старые размещения поверх очищенных выше.
-- Если этих колонок в вашей БД уже нет (например, свежая БД, где таблица
-- storage_systems создавалась заново уже без них) - эти два UPDATE упадут с
-- ошибкой "column does not exist"/"no such column", это ожидаемо и безопасно
-- пропустить (в этом случае Шаг 1 уже полностью достаточен).
UPDATE storage_systems SET rack_cabinet_id = 0, start_unit_pos = 0, end_unit_pos = 0, size_unit = 0
WHERE rack_cabinet_id IS NOT NULL AND rack_cabinet_id > 0;

-- Для СХД, у которых legacy-колонки уже NULL/0 - предыдущий UPDATE их не
-- трогает, что и требуется (не создаём лишний шум в истории изменений).

