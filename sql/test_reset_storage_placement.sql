-- Зачистка данных размещения справочника СХД (models.StorageSystemPlacement)
-- для проверки корректной загрузки размещения из файла Итиллиум и проверки
-- отображения (storagesystemslist.tpl / storagesystemsedit.tpl / канвасы
-- /admin/hwinfra и /admin/infrastructure).
