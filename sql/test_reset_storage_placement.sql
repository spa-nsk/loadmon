-- обычно открывается БД loadmon (psql/DBeaver для postgres, sqlite3 CLI/
-- DB Browser для sqlite3).
--
-- ВАЖНО про повторный запуск приложения после этого скрипта:
-- при каждом старте loadmon вызывается config.migrateStorageSystemsPlacement()
-- (см. config/dbinit.go) - она читает "осиротевшие" (не описанные в Go-
-- структуре, но возможно ещё физически существующие в БД) колонки
-- storage_systems.rack_cabinet_id/start_unit_pos/end_unit_pos/size_unit и,
-- если для СХД ЕЩЁ НЕТ записи в storage_system_placement, переносит их туда
-- заново. Если эти колонки в вашей БД ещё физически существуют (не удалены
-- явным ALTER TABLE, а просто перестали использоваться Go-кодом после
-- миграции на StorageSystemPlacement - RunSyncdb(force=false) их не удаляет),
-- то простой очистки storage_system_placement НЕДОСТАТОЧНО: миграция при
-- следующем старте приложения молча восстановит старые размещения из этих
-- колонок, и тест "загрузка из файла Итиллиум с чистого листа" даст
-- ложно-успешный результат. Поэтому ниже ДВА шага - выполните оба, если не
-- уверены, что старые колонки уже физически удалены (проверить: postgres -
-- \d storage_systems, sqlite3 - PRAGMA table_info(storage_systems)).
-- =============================================================================

-- Шаг 1. Полная очистка новой таблицы размещений СХД (текущий источник
-- истины для "где физически стоит СХД").
--
-- Если нужно очистить размещение НЕ у всех СХД, а только у тестового
-- поднабора (например, только те, что есть в тестовом xlsx-файле Итиллиум) -
-- замените DELETE ниже на вариант с фильтром по serial-номеру через подзапрос,
-- закомментированный чуть ниже.
DELETE FROM storage_system_placement;

